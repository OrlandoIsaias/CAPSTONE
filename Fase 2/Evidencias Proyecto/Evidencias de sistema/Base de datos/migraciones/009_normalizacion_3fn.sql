-- Regiones y comunas
CREATE TABLE regiones (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar NOT NULL UNIQUE
);
CREATE TABLE comunas (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    varchar NOT NULL,
    region_id integer NOT NULL REFERENCES regiones(id),
    CONSTRAINT uq_comuna_region UNIQUE (nombre, region_id)
);
CREATE INDEX idx_comunas_region_id ON comunas(region_id);

INSERT INTO regiones (nombre)
SELECT DISTINCT region FROM organizaciones_validadas WHERE region IS NOT NULL;

INSERT INTO comunas (nombre, region_id)
SELECT DISTINCT o.comuna, r.id
FROM organizaciones_validadas o
JOIN regiones r ON r.nombre = o.region
WHERE o.comuna IS NOT NULL;

ALTER TABLE organizaciones_validadas
    ADD COLUMN comuna_id integer REFERENCES comunas(id);
CREATE INDEX idx_org_comuna_id ON organizaciones_validadas(comuna_id);

UPDATE organizaciones_validadas o
SET comuna_id = c.id
FROM comunas c
JOIN regiones r ON r.id = c.region_id
WHERE c.nombre = o.comuna AND r.nombre = o.region;

