-- 009 - Normalización: tercera forma normal (3FN)
--
-- 3FN exige que ningún atributo no clave dependa de otro atributo no
-- clave (dependencia transitiva). Se corrigen:
--   * organizaciones_validadas: comuna -> region, y comuna -> unidad_sii
--     -> region. Se crean regiones y comunas; la organización guarda solo
--     comuna_id. unidad_sii se elimina: el sistema no la usa.
--   * mensajes_seguimiento: autor_usuario_id -> autor_rol. El rol ya está
--     en usuarios; se elimina la columna y se obtiene con un JOIN.
-- Además se crean los catálogos especies y razas:
--   * razas se identifica por (especie, nombre), porque "Quiltro
--     (mestizo)" y "Otra" existen para perros y para gatos: el nombre de
--     la raza no determina la especie, así que mascotas guarda ambas y
--     las valida con una FK compuesta.
--
-- Fase A: aditiva, compatible con el backend anterior y con el nuevo.
-- Fase B: elimina columnas; ejecutar SOLO con el backend nuevo desplegado.
-- =====================================================================

