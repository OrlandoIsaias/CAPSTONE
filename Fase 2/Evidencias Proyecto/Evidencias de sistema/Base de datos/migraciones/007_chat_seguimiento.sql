-- ============================================================
-- Migración 007 — Chat de seguimiento post-adopción
-- Cada postulación aprobada abre un chat entre el adoptante y el refugio
-- para mostrar cómo está la mascota en su nuevo hogar: texto, fotos, audios
-- y videos. Los archivos viven en Cloudinary; aquí solo se guarda su
-- public_id. Las encuestas de 30 y 90 días dejan un mensaje tipo 'encuesta'.
--
-- También registra la fecha en que el refugio confirma la adopción, que
-- marca desde cuándo se cuentan los 30 y 90 días de las encuestas.
--
-- Solo agrega: no rompe compatibilidad con el código anterior.
-- Idempotente: se puede ejecutar más de una vez sin error.
-- ============================================================

-- ---------- postulaciones ----------
ALTER TABLE "postulaciones" ADD COLUMN IF NOT EXISTS "fecha_adopcion" timestamp;
COMMENT ON COLUMN "postulaciones"."fecha_adopcion" IS 'Cuándo el refugio confirmó la adopción; NULL si no se ha confirmado o se confirmó antes de la migración 007';

-- ---------- mensajes_seguimiento ----------
CREATE TABLE IF NOT EXISTS "mensajes_seguimiento" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "postulacion_id" integer NOT NULL
    REFERENCES "postulaciones" ("id") ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE,
  "autor_usuario_id" integer NOT NULL
    REFERENCES "usuarios" ("id") ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE,
  "autor_rol" varchar NOT NULL,
  "tipo" varchar NOT NULL,
  "texto" text,
  "media_public_id" varchar,
  "duracion_seg" numeric(6,1),
  "creado_en" timestamp NOT NULL DEFAULT (now()),
  "leido_en" timestamp,
  CONSTRAINT chk_mensaje_autor_rol CHECK ("autor_rol" IN ('adoptante', 'refugio')),
  CONSTRAINT chk_mensaje_tipo CHECK ("tipo" IN ('texto', 'imagen', 'audio', 'video', 'encuesta')),
  CONSTRAINT chk_mensaje_texto_largo CHECK ("texto" IS NULL OR length("texto") <= 2000),
  -- Un mensaje de texto o encuesta lleva texto; uno de archivo lleva su public_id.
  CONSTRAINT chk_mensaje_contenido CHECK (
    ("tipo" IN ('texto', 'encuesta') AND coalesce(length(trim("texto")), 0) > 0 AND "media_public_id" IS NULL)
    OR ("tipo" IN ('imagen', 'audio', 'video') AND "media_public_id" IS NOT NULL)
  ),
  CONSTRAINT chk_mensaje_duracion CHECK ("duracion_seg" IS NULL OR "duracion_seg" >= 0)
);

COMMENT ON TABLE "mensajes_seguimiento" IS 'Chat adoptante-refugio de una postulación aprobada (dueño: seguimiento-service)';
COMMENT ON COLUMN "mensajes_seguimiento"."media_public_id" IS 'public_id en Cloudinary, siempre dentro de housefound/seguimiento/<postulacion_id>/';
COMMENT ON COLUMN "mensajes_seguimiento"."texto" IS 'Texto del mensaje, pie de foto o video opcional, o resumen de la encuesta respondida';
COMMENT ON COLUMN "mensajes_seguimiento"."leido_en" IS 'Cuándo lo leyó la otra parte; NULL = no leído';

-- Traer los mensajes de un chat en orden y contar los no leídos.
CREATE INDEX IF NOT EXISTS idx_mensajes_seguimiento_postulacion ON "mensajes_seguimiento" ("postulacion_id", "id");
CREATE INDEX IF NOT EXISTS idx_mensajes_seguimiento_no_leidos
  ON "mensajes_seguimiento" ("postulacion_id") WHERE "leido_en" IS NULL;
